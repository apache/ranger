    @Test
    public void test04_run_positive_processesDuplicatedSerializedRequestsFromTempFile()
            throws Exception {
        PerfTestEngine engine              = newInitializedHiveEngine();
        URL            templateRequestFile =
                requireNonNull(TestPerfTestClient.class.getResource("/testdata/test_requests_hive.json"))
                        .toURI()
                        .toURL();

        String json;

        try (InputStream in = templateRequestFile.openStream()) {
            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            byte[]              buf  = new byte[4096];
            int                 read;

            while ((read = in.read(buf)) != -1) {
                baos.write(buf, 0, read);
            }

            json = new String(baos.toByteArray(), StandardCharsets.UTF_8).trim();
        }

        assertTrue(json.startsWith("[") && json.endsWith("]"));

        String innerPayload = json.substring(1, json.length() - 1).trim();
        byte[] doubledRequests =
                ("[" + innerPayload + "," + innerPayload + "]").getBytes(StandardCharsets.UTF_8);

        Path tempRequestsFile = Files.createTempFile("ranger-double-requests-", ".json");

        tempRequestsFile.toFile().deleteOnExit();

        Files.write(tempRequestsFile, doubledRequests);

        try {
            URL doubledUrl = tempRequestsFile.toUri().toURL();

            PerfTestClient client = new PerfTestClient(engine, 1, doubledUrl, 1);

            assertTrue(client.init());
            client.start();
            client.join(30_000L);
            assertFalse(client.isAlive());
        } finally {
            engine.cleanUp();
        }
    }
