    @FunctionalInterface
    private interface MutedExecutable {
        /**
         * Work run while stdout/stderr are suppressed.
         *
         * @throws Exception if delegated code fails
         */
        void execute() throws Exception;
    }

    private static void runMuted(MutedExecutable executable) throws Exception {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;

        ByteArrayOutputStream sink = new ByteArrayOutputStream();
        PrintStream         mute   = new PrintStream(sink);

        System.setOut(mute);
        System.setErr(mute);

        try {
            executable.execute();
        } finally {
            mute.flush();
            System.setOut(originalOut);
            System.setErr(originalErr);
            mute.close();
        }
    }

