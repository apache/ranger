    @Test
    public void test03_evaluatorClosesGraalBindingsButKeepsSharedEngineUsable() throws Exception {
        GraalScriptEngineCreator creator = new GraalScriptEngineCreator();
        GraalJSScriptEngine firstEngine = (GraalJSScriptEngine) creator.getScriptEngine(null);
        GraalJSScriptEngine secondEngine = (GraalJSScriptEngine) creator.getScriptEngine(null);
        assertNotNull(firstEngine);
        assertNotNull(secondEngine);
        assertSame(firstEngine.getPolyglotEngine(), secondEngine.getPolyglotEngine());

        RangerAccessRequest request = mock(RangerAccessRequest.class);
        when(request.getReadOnlyCopy()).thenReturn(request);

        RangerRequestScriptEvaluator firstEvaluator = new RangerRequestScriptEvaluator(request, firstEngine, false);
        assertEquals(2, ((Number) firstEvaluator.evaluateScript("1 + 1")).intValue());
        Context firstContext = getBindingsContext(firstEngine, firstEvaluator);
        firstEvaluator.close();
        assertThrows(IllegalStateException.class, () -> firstContext.eval("js", "1 + 1"));

        RangerRequestScriptEvaluator failedEvaluator = new RangerRequestScriptEvaluator(request, secondEngine, false);
        assertNull(failedEvaluator.evaluateScript("throw new Error('failure')"));
        Context failedContext = getBindingsContext(secondEngine, failedEvaluator);
        failedEvaluator.close();
        assertThrows(IllegalStateException.class, () -> failedContext.eval("js", "1 + 1"));

        try (RangerRequestScriptEvaluator secondEvaluator = new RangerRequestScriptEvaluator(request, secondEngine, false)) {
            assertEquals(3, ((Number) secondEvaluator.evaluateScript("1 + 2")).intValue());
        }
    }

    @Test
    public void test04_scriptsCannotCloseEvaluatorBindings() throws Exception {
        GraalScriptEngineCreator creator = new GraalScriptEngineCreator();
        GraalJSScriptEngine engine = (GraalJSScriptEngine) creator.getScriptEngine(null);
        assertNotNull(engine);

        RangerAccessRequest request = mock(RangerAccessRequest.class);
        when(request.getReadOnlyCopy()).thenReturn(request);
        when(request.getUser()).thenReturn("test-user");

        Context context;
        try (RangerRequestScriptEvaluator evaluator = new RangerRequestScriptEvaluator(request, engine, false)) {
            assertEquals("undefined", evaluator.evaluateScript("typeof ctx.close"));
            assertEquals(Boolean.TRUE, evaluator.evaluateScript("var closeDenied = false; try { ctx.close(); } catch (e) { closeDenied = e instanceof TypeError; } closeDenied;"));
            assertEquals("test-user", evaluator.evaluateScript("ctx.getUser()"));
            context = getBindingsContext(engine, evaluator);
        }

        assertThrows(IllegalStateException.class, () -> context.eval("js", "1 + 1"));
        try (RangerRequestScriptEvaluator evaluator = new RangerRequestScriptEvaluator(request, engine, false)) {
            assertEquals(3, ((Number) evaluator.evaluateScript("1 + 2")).intValue());
        }
    }

    private Context getBindingsContext(GraalJSScriptEngine engine, RangerRequestScriptEvaluator evaluator) throws Exception {
        Field bindingsField = RangerRequestScriptEvaluator.class.getDeclaredField("bindings");
        bindingsField.setAccessible(true);
        Bindings bindings = (Bindings) bindingsField.get(evaluator);
        SimpleScriptContext scriptContext = new SimpleScriptContext();
        scriptContext.setBindings(bindings, ScriptContext.ENGINE_SCOPE);
        return engine.getPolyglotContext(scriptContext);
    }
